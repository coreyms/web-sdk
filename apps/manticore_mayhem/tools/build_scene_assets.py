def build_landscape(args) -> tuple[dict, list]:
    """the landscape / phone sideways scene from SRC: the 14 files, and the spec block"""
    src = os.path.abspath(os.path.expanduser(args.src))
    fallback = os.path.abspath(os.path.expanduser(args.fallback)) if args.fallback else None

    layers_path = os.path.join(src, 'chain_layers.json')
    if not os.path.isfile(layers_path):
        die(f'no chain_layers.json in {src}')
    layers = json.load(open(layers_path))
    FW, FH = layers['frame']
    tiers = {'full': FW, 'phone': PHONE_WIDTH}
    print(f'source {src}\nframe {FW} x {FH}')

    # ---- the draw order of the moving pieces, as the scene agent lists it ------------------------------------------
    order = []
    for entry in layers['draw_order']:
        for piece in PIECES:
            if piece in entry.lower() and 'sprite' in entry.lower():
                order.append(piece)
    if sorted(order) != sorted(PIECES):
        die(f'draw_order does not name the three sprites once each: {layers["draw_order"]}')
    lower = [e.lower() for e in layers['draw_order']]
    first_sprite = min(i for i, e in enumerate(lower) if 'sprite' in e)
    if not (any('base' in e for e in lower[:first_sprite]) and any('fire' in e for e in lower[:first_sprite])):
        die(f'draw_order: the base and the fire pass must come before the sprites: {layers["draw_order"]}')

    # ---- the points and boxes, both sides read explicitly ----------------------------------------------------------
    points = {}
    boxes = {}
    for side in SIDES:
        pts = layers.get(f'points_{side}')
        if not pts:
            die(f'chain_layers.json has no points_{side}')
        points[side] = {}
        for ours, theirs in POINTS.items():
            name = next((t for t in theirs if t in pts), None)
            if name is None:
                die(f'points_{side} has none of {" / ".join(theirs)}')
            points[side][ours] = [float(pts[name][0]), float(pts[name][1])]
        for piece in PIECES:
            entry = layers.get(f'{piece}_{side}')
            if not entry or 'box_x0y0x1y1' not in entry:
                die(f'chain_layers.json has no {piece}_{side}.box_x0y0x1y1')
            boxes[f'{piece}_{side}'] = [int(v) for v in entry['box_x0y0x1y1']]

    # ---- the sprites -----------------------------------------------------------------------------------------------
    sprites: dict[str, Image.Image] = {}
    shared: set[str] = set()  # folders the json takes sprites from besides SRC
    for piece in PIECES:
        for side in SIDES:
            x0, y0, x1, y1 = boxes[f'{piece}_{side}']
            for st in SETS:
                # the json names the file when a round reuses sprites from another folder; otherwise by name
                named = layers[f'{piece}_{side}'].get(f'file_{st}')
                if named:
                    hits = [os.path.normpath(os.path.join(src, named))]
                    if not os.path.isfile(hits[0]):
                        die(f'{piece}_{side}.file_{st}: {hits[0]} does not exist')
                    if not hits[0].startswith(src + os.sep):
                        shared.add(os.path.dirname(os.path.dirname(hits[0])))
                else:
                    hits = sorted(glob.glob(os.path.join(src, 'sprites', f'*{piece}_{side}_{st}*.png')))
                    if len(hits) != 1:
                        die(f'sprites/*{piece}_{side}_{st}*.png: {len(hits)} files, wanted exactly one')
                im = Image.open(hits[0]).convert('RGBA')
                if im.size != (x1 - x0, y1 - y0):
                    die(f'{os.path.basename(hits[0])} is {im.size}, its box in chain_layers.json is {(x1 - x0, y1 - y0)}')
                sprites[f'{piece}_{side}_{st}'] = im

    # ---- the swag pins, from the day sprites (see PIN_ALPHA) -------------------------------------------------------
    for side in SIDES:
        x0, y0, _, _ = boxes[f'swag_{side}']
        alpha = np.asarray(sprites[f'swag_{side}_day'])[..., 3] > PIN_ALPHA
        rows = np.nonzero(alpha.any(1))[0]
        last = rows[0]
        for r in rows[1:]:
            if r - last > PIN_GAP:
                break
            last = r
        xs = np.nonzero(alpha[last])[0]
        points[side]['swagPin'] = [round(float(x0 + xs.mean()), 1), float(y0 + last)]
        below = int((rows > last).sum())
        print(f'  swag {side}: pinned at {points[side]["swagPin"]} (the json\'s lowest visible point {points[side]["swagEnd"]}'
              + (f', {below} rows show again under the pin and stay still)' if below else ')'))

    # ---- the big layers --------------------------------------------------------------------------------------------
    # a round that re-rendered only the chains keeps its bases and fire pass in the folder its json reuses sprites from
    if not fallback and len(shared) == 1:
        fallback = shared.pop()
    fore = {st: Image.open(find(src, fallback, f'{st}_base_{FW}.png')).convert('RGBA') for st in SETS}
    for st, im in fore.items():
        if im.size != (FW, FH):
            die(f'{st} base is {im.size}, the frame is {(FW, FH)}')
    fire_src = Image.open(find(src, fallback, f'fire_pass_{FW}.png', f'fire_pass_{FW // 2}.png')).convert('RGBA')
    # on black: the additive blend adds exactly rgb x alpha, which is what the scene agent's composites add
    fire_black = Image.new('RGBA', fire_src.size, (0, 0, 0, 255))
    fire_black.alpha_composite(fire_src)
    fire_black = fire_black.convert('RGB')
    back_names = {'day': 'backdropv2_2560_digital-art-4x.png', 'night': 'backdrop_night_2560_digital-art-4x.png'}
    back = {st: Image.open(find(os.path.expanduser(args.backdrops), None, name)).convert('RGB') for st, name in back_names.items()}

    spec = {
        'source': os.path.basename(src),
        'frame': [FW, FH],
        'order': order,
        'points': points,
        'tiers': {},
    }
    report: list[tuple[str, int, int, int]] = []  # name, bytes, w, h

    for tier, width in tiers.items():
        s = width / FW
        size = (width, round(FH * s))
        fire_size = (round(size[0] * FIRE_SHARE), round(size[1] * FIRE_SHARE))
        suffix = '' if tier == 'full' else f'-{tier}'
        for st in SETS:
            # the painting is a pixel taller than the frame: fitted to it, as in the scene agent's composites
            b = back[st].resize(size, Image.LANCZOS)
            name = f'backdrop-{st}{suffix}.webp'
            report.append((name, save_webp(b, name, Q_BACKDROP), *size))
            report_band(name, b, 'Q_BACKDROP')
            f = resize_rgba(fore[st], size)
            name = f'fore-{st}{suffix}.webp'
            report.append((name, save_webp(f, name, Q_FORE, alpha_quality=100), *size))
        fp = fire_black.resize(fire_size, Image.LANCZOS)
        name = f'fire{suffix}.webp'
        report.append((name, save_webp(fp, name, Q_FIRE), *fire_size))
        # printed only: the pass is dim render noise over black, which the encoder smooths (looked at 4x gain, 2026-10-10:
        # no steps at quality 90); the count says nothing about steps there
        report_band(name, fp, None)

        # the sprites on this tier's texel grid: the box grown to whole texels plus the margin, mapped back to the frame
        tier_boxes = {}
        cells: dict[str, Image.Image] = {}
        for key, (x0, y0, x1, y1) in boxes.items():
            t0x, t0y = int(np.floor(x0 * s)) - SPRITE_MARGIN, int(np.floor(y0 * s)) - SPRITE_MARGIN
            t1x, t1y = int(np.ceil(x1 * s)) + SPRITE_MARGIN, int(np.ceil(y1 * s)) + SPRITE_MARGIN
            tier_boxes[key] = [round(v / s, 4) for v in (t0x, t0y, t1x, t1y)]
            ox, oy = int(np.floor(t0x / s)) - 4, int(np.floor(t0y / s)) - 4
            cw, ch = int(np.ceil(t1x / s)) + 4 - ox, int(np.ceil(t1y / s)) + 4 - oy
            for st in SETS:
                canvas = Image.new('RGBA', (cw, ch), (0, 0, 0, 0))
                canvas.paste(sprites[f'{key}_{st}'], (x0 - ox, y0 - oy))
                src_box = (t0x / s - ox, t0y / s - oy, t1x / s - ox, t1y / s - oy)
                if s == 1:
                    cells[f'{key}_{st}'] = canvas.crop(tuple(int(v) for v in src_box))
                else:
                    cells[f'{key}_{st}'] = resize_rgba(canvas, (t1x - t0x, t1y - t0y), box=src_box)
        names = sorted(cells)
        padded = [(cells[n].size[0] + ATLAS_PAD, cells[n].size[1] + ATLAS_PAD) for n in names]
        best = None
        for aw in range(max(w for w, _ in padded), sum(w for w, _ in padded) + 1, 4):
            pos, ah = skyline_pack(padded, aw)
            if pos and (best is None or aw * ah < best[0]):
                best = (aw * ah, aw, ah, pos)
        _, aw, ah, pos = best
        atlas = Image.new('RGBA', (aw, ah), (0, 0, 0, 0))
        frames = {}
        for n, (px, py) in zip(names, pos):
            atlas.paste(cells[n], (px, py))
            w, h = cells[n].size
            frames[f'scene_{n}'] = {'frame': {'x': px, 'y': py, 'w': w, 'h': h}, 'rotated': False, 'trimmed': False,
                                    'spriteSourceSize': {'x': 0, 'y': 0, 'w': w, 'h': h}, 'sourceSize': {'w': w, 'h': h}}
        image = f'chains{suffix}.webp'
        nbytes = save_webp(atlas, image, Q_SPRITES, alpha_quality=100)
        meta = {'image': image, 'format': 'RGBA8888', 'size': {'w': aw, 'h': ah}, 'scale': '1',
                'pngHash': hashlib.md5(open(os.path.join(OUT, image), 'rb').read()).hexdigest()[:8]}
        jpath = os.path.join(OUT, f'chains{suffix}.json')
        open(jpath, 'w').write(json.dumps({'frames': frames, 'meta': meta}, indent=1) + '\n')
        report.append((f'chains{suffix}.json + .webp', nbytes + os.path.getsize(jpath), aw, ah))

        # the check: the shipped cells laid back over the frame against the source sprites (alpha weighted colour)
        got_atlas = Image.open(os.path.join(OUT, image)).convert('RGBA')
        worst = 0.0
        for n, (px, py) in zip(names, pos):
            key, st = n.rsplit('_', 1)
            x0, y0, x1, y1 = boxes[key]
            w, h = cells[n].size
            cell = got_atlas.crop((px, py, px + w, py + h))
            b = tier_boxes[key]
            # back onto the source sprite's own pixels: its box inside the cell, in this tier's texels
            back_at = cell.convert('RGBa').resize((x1 - x0, y1 - y0), Image.BILINEAR, box=((x0 - b[0]) * s, (y0 - b[1]) * s, (x1 - b[0]) * s, (y1 - b[1]) * s))
            want = sprites[n]
            d = np.abs(np.asarray(back_at).astype(float) - np.asarray(want.convert('RGBa')).astype(float)).mean()
            worst = max(worst, d)
        print(f'  chains{suffix}: atlas {aw} x {ah}, {len(names)} frames, laid back over the frame the worst sprite differs by a mean of {worst:.2f} of 255')
        spec['tiers'][tier] = {'size': list(size), 'fire': list(fire_size), 'boxes': tier_boxes}

    frame_back = {st: back[st].resize((FW, FH), Image.LANCZOS) for st in SETS}
    spec['sky'], sky_tiers, sky_report = build_sky(args, FW, FH, frame_back, tiers)
    for tier in tiers:
        spec['tiers'][tier].update(sky_tiers[tier])
    return spec, report, sky_report


def build_sky_only(args, wide: dict) -> list:
    """--sky alone: the sky set from the backdrops, into the landscape block already on disk"""
    FW, FH = wide['frame']
    back_names = {'day': 'backdropv2_2560_digital-art-4x.png', 'night': 'backdrop_night_2560_digital-art-4x.png'}
    back = {st: Image.open(find(os.path.expanduser(args.backdrops), None, name)).convert('RGB').resize((FW, FH), Image.LANCZOS) for st, name in back_names.items()}
    wide['sky'], sky_tiers, report = build_sky(args, FW, FH, back, {tier: entry['size'][0] for tier, entry in wide['tiers'].items()})
    for tier in sky_tiers:
        wide['tiers'][tier].update(sky_tiers[tier])
    return report


def build_portrait(folder: str) -> tuple[dict, list]:
    """the PORTRAIT scene from its own folder (portrait_layers.json names the files): backdrop, foreground and fire pass
    only, there are no moving pieces. Same tiers rule (full = the frame, phone = PORTRAIT_PHONE_WIDTH wide), same
    qualities, same checks."""
    folder = os.path.abspath(os.path.expanduser(folder))
    layers_path = os.path.join(folder, 'portrait_layers.json')
    if not os.path.isfile(layers_path):
        die(f'no portrait_layers.json in {folder}')
    layers = json.load(open(layers_path))
    FW, FH = layers['frame']
    files = layers['files']
    print(f'portrait source {folder}\nframe {FW} x {FH}')

    def named(key: str, *alt: str) -> str:
        for k in (key, *alt):
            if k in files and os.path.isfile(os.path.join(folder, files[k])):
                return os.path.join(folder, files[k])
        die(f'portrait_layers.json files.{key}: not named or not found in {folder}')

    back = {st: Image.open(named(f'backdrop_{st}')).convert('RGB') for st in SETS}
    fore = {st: Image.open(named(f'base_{st}')).convert('RGBA') for st in SETS}
    for st in SETS:
        if back[st].size != (FW, FH) or fore[st].size != (FW, FH):
            die(f'portrait {st}: backdrop {back[st].size}, base {fore[st].size}, the frame is {(FW, FH)}')
    # the full size pass when there is one (both tiers are cut from it), else the half size one
    fire_src = Image.open(named('fire_pass_full', 'fire_pass')).convert('RGBA')
    fire_black = Image.new('RGBA', fire_src.size, (0, 0, 0, 255))
    fire_black.alpha_composite(fire_src)
    fire_black = fire_black.convert('RGB')
    # where the solid 3D begins: the first row the foreground covers (more than half, across the frame)
    cover = np.asarray(fore['day'])[..., 3].mean(1) / 255
    solid = int(np.argmax(cover > 0.5))
    notes = layers.get('backdrop_notes', {})
    for key in ('sky_extended_above_row', 'fill_below_row'):
        if key not in notes:
            die(f'portrait_layers.json backdrop_notes has no {key}')
    spec = {
        'source': os.path.basename(folder),
        'frame': [FW, FH],
        # rows of the frame: the painting, and the soft mist fill between it and the terrace's far edge (the board
        # is meant to cover the fill: tools/manticore/scene_probe.js checks that on every portrait screen)
        'painting': [int(notes['sky_extended_above_row']), int(notes['fill_below_row'])],
        'fill': [int(notes['fill_below_row']), solid],
        'tiers': {},
    }
    print(f'  the mist fill: rows {spec["fill"][0]} to {spec["fill"][1]} (the foreground covers the frame from row {solid})')
    report: list[tuple[str, int, int, int]] = []
    for tier, width in {'full': FW, 'phone': PORTRAIT_PHONE_WIDTH}.items():
        s = width / FW
        size = (width, round(FH * s))
        fire_size = (round(size[0] * FIRE_SHARE), round(size[1] * FIRE_SHARE))
        suffix = '' if tier == 'full' else f'-{tier}'
        for st in SETS:
            b = back[st].resize(size, Image.LANCZOS)
            name = f'portrait-backdrop-{st}{suffix}.webp'
            report.append((name, save_webp(b, name, Q_BACKDROP), *size))
            report_band(name, b, 'Q_BACKDROP')
            name = f'portrait-fore-{st}{suffix}.webp'
            report.append((name, save_webp(resize_rgba(fore[st], size), name, Q_FORE, alpha_quality=100), *size))
        fp = fire_black.resize(fire_size, Image.LANCZOS)
        name = f'portrait-fire{suffix}.webp'
        report.append((name, save_webp(fp, name, Q_FIRE), *fire_size))
        report_band(name, fp, None)
        spec['tiers'][tier] = {'size': list(size), 'fire': list(fire_size)}
    return spec, report


def read_spec(name: str) -> dict | None:
    """a block of the sceneSpec.ts already on disk (the side this run does not rebuild is kept as it is)"""
    if not os.path.isfile(SPEC):
        return None
    text = open(SPEC).read()
    mark = f'export const {name} = '
    if mark not in text:
        return None
    body = text[text.index(mark) + len(mark):]
    return json.loads(body[:body.index(' as const;')])


