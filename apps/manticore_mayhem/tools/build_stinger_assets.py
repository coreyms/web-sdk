def write_reference(M: Path, path: Path) -> None:
    """the reference compositor's vertices (model/scripts/L0_lib.py Layered.layer_mesh, 1x px) for the node self check"""
    sys.path.insert(0, str(M / "scripts"))
    import L0_lib  # noqa: E402

    Ld = L0_lib.Layered(str(M / "layered" / "stinger_layered.json"))
    cases = [("idle_all", 0, None), ("idle_all", 17, None), ("idle_all", 104, None), ("land_flare", 0, None), ("land_flare", 6, None), ("land_flare", 30, None), ("tier_flare", 4, 0), ("tier_flare", 7, 53), ("tier_flare", 12, 95), ("tier_flare", 21, 100)]
    out = []
    for action, f, P in cases:
        for name in L0_lib.MOVERS:
            L = Ld.by[name]
            gain = Ld.J.get("tier_gain", {}).get(name, [1.0] * 105)[P] if P is not None else 1.0
            v, _, _ = Ld.layer_mesh(L, action, f, P, gain)
            out.append({"action": action, "frame": f, "idleFrom": P, "layer": name, "vertices": [round(float(x), 4) for x in (np.asarray(v) / Ld.J["texture_scale"]).ravel()]})
    path.write_text(json.dumps(out))
    print(f"reference: {len(out)} layer poses -> {path}")


