#!/usr/bin/env python
"""Game assets for the animated win plaque ("stinger"): the layered cut-outs, every overlay sprite, the
baked titles and the forged glyph atlas, plus the motion tracks and the overlay recipes as runtime data.

  /Users/corey/Projects/stake-engine/math-sdk/env/bin/python tools/build_stinger_assets.py [--src DIR] [--reference FILE]

Sources (read only, never written), under --src (default ~/Desktop/Manticore Mayhem/images/ui):
  model/layered/stinger_layered.json + 15 PNGs at 2x     layers in z order, mesh topology, idle_all, the two flares, tier_gain
  model/stinger_{vein,glint,barb,eye_flare,embers}_fx.json, model/stinger_v5_eye_anchors.json     the overlay recipes
  drafts/stinger_{veins,glint,barb,eyes_v2,final_fx}_review/sprites/4x/*.png                      the overlay sprites
  drafts/text_assets/titles/*.png, plaque-glyphs.{png,json}, plaque-text.json                     tools/build_plaque_text.py

Outputs (static/assets/ui/stinger), everything regenerated by one run:
  stinger-<atlas>.json|webp        the FULL tier: plaque (the 15 cut-outs), fx (veins, slab, barbs, eyes, embers, star),
                                   glint (the 14 slices), titles, glyphs. Pixi spritesheet json, frames stg_<name>.
  stinger-<atlas>-half.json|webp   the PHONE tier twins (game/deviceTier.ts), same frame names
  stinger-motion.bin               int16 LE: per mesh layer idle_all (105 frames, absolute, 1/32 px) then tier_flare (22)
                                   and land_flare (31) deltas (linear: dx, dy; polar: theta, rho - 1; scales in the json)
  stinger.json                     everything the runtime reads: layers (uvs 0..1, indices, pivots, bin offsets, tier_gain),
                                   sprite rects, the five overlay recipes, barb tracks as idle + flare deltas, glyph
                                   metrics, kerning, title boxes, copy and the screen layouts

UNITS. Every position and size in stinger.json is in SHIP pixels of the 946 x 532 plaque frame (the "1x" of the source
notes), whatever resolution a texture ships at: `sprites[name]` = [x, y, w, h] is where the (trimmed) image sits, in frame
coordinates for placed sprites and relative to its anchor for anchored ones (barbs, star, eye flare, embers). The runtime
scales each sprite by w / texture width, so a tier is a file swap and nothing else.

RESOLUTION (TIERS below; the budget table at the end is the check, target about 24 MB of RGBA8 with mip chains):
the renderer caps the device pixel ratio at 1.5 and the plaque frame is about 0.4 of a desktop screen's width, so a ship
pixel is drawn at 0.55 (1280 wide at DPR 1) to about 1.3 device px (1920 at DPR 1.5, a tablet in portrait); a phone draws
it at 0.6 to 0.95. FULL ships the cut-outs, veins, titles and glyphs at 1.5x, PHONE at 1x. The glint slices are soft
highlights and the known hog (14 tall slices, 1.05 megapixels at 1x, 3 to 17 % filled, so a bbox trim gains nothing):
1x on FULL, 0.75x on PHONE, in their own atlas without a mip chain. Titles are baked at 3x of a 52.7 px cap and drawn
smaller (cap 50 / 32 / 36): each ships at the tier scale of its DRAWN size. The glyph atlas ships at the tier scale of
the largest use (the 64 px amount). Lids and embers are tiny and ship at 2x on both tiers (an ember is never drawn above
its native size), the vein wash and the slab mask (soft shapes) at 0.5x.
"""
