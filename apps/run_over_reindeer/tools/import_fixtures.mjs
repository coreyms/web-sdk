// @ts-nocheck (a plain node script; the app type check should not read it)
// Copies the math's REAL fixture books into the app as dev fixtures (read only under math-sdk).
//
//   node tools/import_fixtures.mjs
//
// Source: math-sdk/games/run_over_reindeer/fixtures/ (contract 2026-11-09b; UNTUNED books, never for upload):
// showcase_books.json (the named showcase rounds) and books_base.json (for two plain no-win spins, which the
// showcase list does not have). Writes src/fixtures/showcaseBooks.ts. Run it again when the math agent remakes
// the fixtures. The books are copied byte for byte: nothing in them is changed or worked out here.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = dirname(dirname(fileURLToPath(import.meta.url)));
const MATH = join(APP, '..', '..', '..', 'math-sdk', 'games', 'run_over_reindeer', 'fixtures');

const showcase = JSON.parse(readFileSync(join(MATH, 'showcase_books.json'), 'utf8'));
const base = JSON.parse(readFileSync(join(MATH, 'books_base.json'), 'utf8'));

const rounds = [];
const seen = new Map(); // mode:sim -> the first key that used that book
for (const entry of showcase) {
	const id = `${entry.mode}:${entry.sim}`;
	rounds.push({ name: entry.key, mode: entry.mode, sim: entry.sim, note: entry.why, sameBookAs: seen.get(id) ?? null, payoutMultiplier: entry.book.payoutMultiplier / 100, events: seen.has(id) ? null : entry.book.events });
	if (!seen.has(id)) seen.set(id, entry.key);
}
// two plain spins that pay nothing: the first two of the base set with one event besides finalWin and no strike
const plain = base.filter((b) => b.payoutMultiplier === 0 && b.events.length === 2 && b.events[0].type === 'reveal').slice(0, 2);
plain.forEach((b, i) => rounds.push({ name: `no_win_${i + 1}`, mode: 'base', sim: b.id, note: 'base spin, nothing lines up', sameBookAs: null, payoutMultiplier: 0, events: b.events }));

const out = `// AUTO-GENERATED by tools/import_fixtures.mjs from math-sdk/games/run_over_reindeer/fixtures (contract 2026-11-09b).
// REAL books from the math's own engine, copied as they are. UNTUNED: not the game's books, never for upload.
// DEV ONLY: nothing but src/fixtures/fixtureRgs.ts imports this, and a production build does not include it.
import type { BookEvent } from '../game/typesBookEvent';

export type ShowcaseRound = {
	/** the showcase key (fixtures/README.md) */
	name: string;
	mode: 'base' | 'bonus' | 'super';
	/** the simulation id: the book can be made again from (mode, sim) */
	sim: number;
	note: string;
	/** several showcase keys point at one book: the key that holds its events */
	sameBookAs: string | null;
	/** the round's payout in bet multiples */
	payoutMultiplier: number;
	events: BookEvent[] | null;
};

export const SHOWCASE_ROUNDS = ${JSON.stringify(rounds)} as unknown as ShowcaseRound[];
`;
writeFileSync(join(APP, 'src', 'fixtures', 'showcaseBooks.ts'), out);
console.log(`import_fixtures: ${rounds.length} rounds (${rounds.filter((r) => r.events).length} books), ${(out.length / 1024).toFixed(0)} KB`);
for (const r of rounds) console.log(`  ${r.name.padEnd(28)} ${r.mode.padEnd(6)} sim ${String(r.sim).padEnd(6)} ${String(r.payoutMultiplier).padStart(8)}x  ${r.events ? r.events.length + ' events' : 'same book as ' + r.sameBookAs}`);
