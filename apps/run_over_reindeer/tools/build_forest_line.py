# THE FOREST'S TREE LINE (2026-11-19, Corey: "on portrait view the reindeer is walking on the trees ... make the walk
# area so that's off limits"): for each scene kit's forest picture, the lowest row of tree pixels in each of COLUMNS
# columns, as a share of the picture's height (alpha 128 or more counts as trees; the soft fade under the bottom row of
# trunks does not). Writes src/game/forestLineSpec.ts (generated). Pixel reading only; the art is untouched.
#
#   math-sdk/env/bin/python web-sdk/apps/run_over_reindeer/tools/build_forest_line.py
import json
import os
import re

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
COLUMNS = 48


def main():
    spec_src = open(os.path.join(APP, "src", "game", "sceneArtSpec.ts")).read()
    kits = re.findall(r'\n\t"?(\w+)"?:\s*\{\s*\n\t\t"?field', spec_src)
    files = re.findall(r'"forest":\s*\{\s*"file":\s*"([^"]+)"', spec_src)
    out = {}
    for kit, f in zip(kits, files):
        a = np.asarray(Image.open(os.path.join(APP, "static", "assets", f)).convert("RGBA"))[..., 3]
        h, w = a.shape
        line = []
        for i in range(COLUMNS):
            band = a[:, int(i * w / COLUMNS):int((i + 1) * w / COLUMNS)]
            rows = np.where(band.max(axis=1) >= 128)[0]
            line.append(round(float(rows.max() + 1) / h, 4) if len(rows) else 0.0)
        out[kit] = {"file": f, "line": line}
        print(f"  {kit}: {f} tree line {min(line):.3f} to {max(line):.3f} of the height")
    path = os.path.join(APP, "src", "game", "forestLineSpec.ts")
    with open(path, "w") as fh:
        fh.write("// AUTO-GENERATED by tools/build_forest_line.py from the scene kits' forest pictures. Do not edit: run it again.\n")
        fh.write("// Per kit: the lowest row of tree pixels in each of `line.length` equal columns, a share of the picture's height.\n")
        fh.write(f"export const FOREST_LINE = {json.dumps(out, indent=chr(9))} as const;\n")
    print(f"  wrote {os.path.relpath(path, APP)}")


if __name__ == "__main__":
    main()
