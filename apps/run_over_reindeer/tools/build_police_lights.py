"""THE POLICE CAR'S LIGHT BAR (Corey 2026-11-15: "We should do the Police car light ups for when there is a win with
them in code"): measures where the red and the blue lens sit on the police car (H4_R, H4_L) in the desktop and the phone
symbol atlases, and writes src/game/policeLightSpec.ts (generated). The lights themselves are drawn in code
(game/road/policeLights.ts): no new art.

Run with the math env's Python (Pillow, numpy):
    math-sdk/env/bin/python web-sdk/apps/run_over_reindeer/tools/build_police_lights.py [--report <file.json>]

THE RULE: a lens is the largest connected patch of its color inside the light bar (the middle third of the car's width,
its upper 45 percent): red = R >= 150, G <= 90, B <= 90; blue = B >= 150, R <= 100, G <= 140; alpha >= 200. Its centre
and size are given in road px from the sprite's anchor (the frame's bottom centre), at the symbol's built road size
(game/roadArtSpec.ts), so the same numbers serve both tiers; the phone atlas is measured too and must agree.
"""
import argparse
import json
import os

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
SYM = os.path.join(APP, "static", "assets", "symbols")


def road_size(frame):
    src = open(os.path.join(APP, "src", "game", "roadArtSpec.ts")).read()
    d = json.loads(src[src.index("{"): src.rindex("}") + 1])
    s = d["symbols"][frame]
    return s["width"], s["height"]


def largest(mask):
    """the largest 4-connected patch of a boolean mask: its pixel list (ys, xs)"""
    seen = np.zeros_like(mask, dtype=bool)
    best = ([], [])
    H, W = mask.shape
    for y0, x0 in zip(*np.nonzero(mask)):
        if seen[y0, x0]:
            continue
        stack = [(y0, x0)]
        seen[y0, x0] = True
        ys, xs = [], []
        while stack:
            y, x = stack.pop()
            ys.append(y)
            xs.append(x)
            for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                v, u = y + dy, x + dx
                if 0 <= v < H and 0 <= u < W and mask[v, u] and not seen[v, u]:
                    seen[v, u] = True
                    stack.append((v, u))
        if len(ys) > len(best[0]):
            best = (ys, xs)
    return np.array(best[0]), np.array(best[1])


def measure(atlas, frame):
    meta = json.load(open(os.path.join(SYM, atlas + ".json")))
    f = meta["frames"][frame]["frame"]
    im = np.asarray(Image.open(os.path.join(SYM, atlas + ".webp")).convert("RGBA")).astype(int)
    a = im[f["y"]: f["y"] + f["h"], f["x"]: f["x"] + f["w"]]
    H, W = a.shape[:2]
    win = np.zeros((H, W), dtype=bool)
    win[: int(H * 0.45), W // 3: 2 * W // 3] = True
    r, g, b, al = a[..., 0], a[..., 1], a[..., 2], a[..., 3]
    masks = {
        "red": win & (al >= 200) & (r >= 150) & (g <= 90) & (b <= 90),
        "blue": win & (al >= 200) & (b >= 150) & (r <= 100) & (g <= 140),
    }
    rw, rh = road_size(frame)
    out = {}
    for color, m in masks.items():
        ys, xs = largest(m)
        cx, cy = (xs.min() + xs.max() + 1) / 2, (ys.min() + ys.max() + 1) / 2
        # road px from the anchor (bottom centre)
        out[color] = {
            "x": round((cx - W / 2) * rw / W, 2),
            "y": round((cy - H) * rh / H, 2),
            "w": round((xs.max() - xs.min() + 1) * rw / W, 2),
            "h": round((ys.max() - ys.min() + 1) * rh / H, 2),
            "pixels": int(len(xs)),
        }
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report")
    args = ap.parse_args()
    table = {}
    report = {}
    for frame in ("H4_R", "H4_L"):
        full = measure("symbols", frame)
        phone = measure("symbols-phone", frame)
        report[frame] = {"full": full, "phone": phone}
        for color in ("red", "blue"):
            d = max(abs(full[color][k] - phone[color][k]) for k in ("x", "y"))
            if d > 2.5:
                raise SystemExit(f"{frame} {color}: the phone atlas puts the lens {d:.1f} road px from the desktop one")
        table[frame] = {c: {k: full[c][k] for k in ("x", "y", "w", "h")} for c in ("red", "blue")}
    body = json.dumps({"frames": table}, indent="\t")
    with open(os.path.join(APP, "src", "game", "policeLightSpec.ts"), "w") as fh:
        fh.write(
            "// AUTO-GENERATED by tools/build_police_lights.py from the symbol atlases. Do not edit: change the tool and run it\n"
            "// again. Each lens of the police car's light bar: its centre (x, y) and size (w, h), road px from the sprite's\n"
            "// anchor (the frame's bottom centre) at the symbol's built size; the phone atlas agrees to 2.5 road px.\n"
            f"export const POLICE_LIGHTS = {body} as const;\n"
        )
    if args.report:
        json.dump(report, open(args.report, "w"), indent=1)
    print(json.dumps(report, indent=1))


main()
