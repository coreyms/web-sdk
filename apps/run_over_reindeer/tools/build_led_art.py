"""THE LED BILLBOARD'S PICTURES (Corey 2026-11-16, led_billboard_r2_2026-11-16: "That looks amazing"; game/landing/ledSign.ts):
packs the approved mock's own pictures (its work/art/: the reindeer's eight run frames, the sleigh, Grandma's car, the three
column characters and the cloud, already at the sizes the mock draws them from) into ONE small sheet the sign draws its
screens from, at one pixel per dot, on a 2D canvas: static/assets/landing/led-art.webp (quality 90, its alpha lossless: the LED punch keys on
alpha) and src/game/ledArtSpec.ts (generated: each picture's place on the sheet). The run strip stays whole (its eight
125 x 108 frames side by side, as the mock cuts them).

THE RIDERS (Corey 2026-11-19): Grandma's car and Santa's sleigh carry their riders, seated as the road board seats them
(tools/led_seated.py, as tools/build_scoreboard_art.py). Their frames carry `vehicle`: the vehicle's box in the picture
(px), which the press screen fits into its reel cell (game/landing/ledScreens.ts drawFit), the rider rising above it.

Run with the math env's Python (Pillow, numpy, scipy):
    math-sdk/env/bin/python web-sdk/apps/run_over_reindeer/tools/build_led_art.py
"""
import json
import os

from PIL import Image

from led_seated import compose
from _paths import ART_SRC  # noqa: E402  (tools/_paths.py: the app's art-src/ folder)

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
SRC = os.path.join(ART_SRC, "led_billboard_r2_2026-11-16/work/art")
OUT = os.path.join(APP, "static", "assets", "landing")
SPEC = os.path.join(APP, "src", "game", "ledArtSpec.ts")
NAMES = ["run_strip", "car", "sleigh", "reindeer_col", "santa_col", "grandma_col", "cloud"]
GAP = 2
# the vehicles drawn with their rider: the atlas frame each one is (the mock's pictures face left)
SEATED = {"car": "H1_L", "sleigh": "W_L"}


def main():
    os.makedirs(OUT, exist_ok=True)
    ims = {n: Image.open(os.path.join(SRC, n + ".png")).convert("RGBA") for n in NAMES}
    boxes = {}
    for n, fr in SEATED.items():
        ims[n], boxes[n] = compose(fr, ims[n].width)
    # row 1: the run strip; row 2: the rest, left to right
    strip = ims["run_strip"]
    rest = [n for n in NAMES if n != "run_strip"]
    row2w = sum(ims[n].width for n in rest) + GAP * (len(rest) - 1)
    row2h = max(ims[n].height for n in rest)
    W = max(strip.width, row2w)
    H = strip.height + GAP + row2h
    sheet = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    frames = {"run_strip": {"x": 0, "y": 0, "w": strip.width, "h": strip.height}}
    sheet.paste(strip, (0, 0))
    x = 0
    y = strip.height + GAP
    for n in rest:
        im = ims[n]
        sheet.paste(im, (x, y))
        frames[n] = {"x": x, "y": y, "w": im.width, "h": im.height}
        if n in boxes:
            frames[n]["vehicle"] = boxes[n]
        x += im.width + GAP
    path = os.path.join(OUT, "led-art.webp")
    sheet.save(path, "WEBP", quality=90, alpha_quality=100, method=6)
    with open(SPEC, "w") as f:
        f.write("// AUTO-GENERATED by tools/build_led_art.py from the approved LED billboard mock's pictures. Do not edit: run the\n")
        f.write("// tool again. The pictures the LED billboard's screens draw (game/landing/ledScreens.ts), their place on\n")
        f.write("// static/assets/landing/led-art.webp in px; the run strip holds the reindeer's eight 125 x 108 run frames.\n")
        f.write("export const LED_ART = " + json.dumps({"width": W, "height": H, "frames": frames}, indent="\t") + " as const;\n")
    print(W, H, os.path.getsize(path), "bytes")


if __name__ == "__main__":
    main()
